"""Build a source candidate with no execution permission on candidate files.

Only system toolchain directories permit execution. The target is not supplied
as a compiler input. This worker fails closed without Landlock ABI 3.
"""
import ctypes
import json
import os
from pathlib import Path
import subprocess
import sys


def restrict(project):
    for root in ('/usr', '/lib', '/lib64', '/bin'):
        trusted = Path(root).resolve()
        if project == trusted or trusted in project.parents:
            raise ValueError('Candidate project must be outside system toolchain directories')
    libc = ctypes.CDLL(None, use_errno=True)
    libc.syscall.restype = ctypes.c_long
    def syscall(number, *args):
        result = libc.syscall(ctypes.c_long(number), *args)
        if result < 0:
            raise OSError(ctypes.get_errno(), os.strerror(ctypes.get_errno()))
        return result
    # Linux x86-64, matching the native backend's supported platform.
    if os.uname().machine != 'x86_64':
        raise ValueError('Recovery builds require Linux x86-64')
    abi = syscall(444, 0, 0, 1)
    if abi < 3:
        raise ValueError('Recovery builds require Landlock ABI >= 3')
    handled = (1 << 15) - 1
    class Ruleset(ctypes.Structure):
        _fields_ = [('handled_access_fs', ctypes.c_uint64)]
    class Rule(ctypes.Structure):
        _layout_ = 'ms'
        _pack_ = 1
        _fields_ = [('allowed_access', ctypes.c_uint64), ('parent_fd', ctypes.c_int32)]
    attr = Ruleset(handled)
    rules = syscall(444, ctypes.byref(attr), ctypes.sizeof(attr), 0)
    def grant(path, access):
        fd = os.open(path, os.O_PATH | os.O_CLOEXEC)
        try:
            rule = Rule(access, fd)
            syscall(445, rules, 1, ctypes.byref(rule), 0)
        finally:
            os.close(fd)
    try:
        for path in ('/usr', '/lib', '/lib64', '/bin'):
            if Path(path).exists():
                grant(path, 1 | 4 | 8)  # execute, read file, read directory
        if Path('/etc/ld.so.cache').exists():
            grant('/etc/ld.so.cache', 4)
        grant('/dev/null', 2 | 4)
        # Files and directories only; no execute, device nodes, sockets or links.
        grant(str(project), 2 | 4 | 8 | 16 | 32 | 128 | 256 | 16384)
        if libc.prctl(38, 1, 0, 0, 0):
            raise OSError(ctypes.get_errno(), 'PR_SET_NO_NEW_PRIVS failed')
        syscall(446, rules, 0)
    finally:
        os.close(rules)


def main():
    project = Path.cwd().resolve()
    manifest = json.loads((project / 'build.json').read_text())
    restrict(project)
    (project / 'build-isolation.json').write_text(json.dumps({
        'landlock': True, 'candidate_execution_allowed': False,
        'target_path_passed_to_compiler': False}))
    env = dict(PATH='/usr/bin:/bin', LANG='C', LC_ALL='C', TZ='UTC',
               TMPDIR=str(project / 'tmp'), SOURCE_DATE_EPOCH='0')
    (project / 'tmp').mkdir(exist_ok=True)
    command = manifest['command']
    with (project / 'compiler-version.txt').open('w') as version:
        subprocess.run([command[0], '--version'], env=env, check=True, stdout=version)
    # Manifest is generated by the parent; no shell and no user build scripts.
    result = subprocess.run(command, env=env, check=False)
    if result.returncode:
        return result.returncode
    return 0


if __name__ == '__main__':
    try:
        raise SystemExit(main())
    except (OSError, ValueError) as error:
        print(f'Recovery build unavailable: {error}', file=sys.stderr)
        raise SystemExit(125)
